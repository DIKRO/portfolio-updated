import { headers } from "next/headers";
import { Lang } from "@/content/lang";

// Язык интерфейса выбирается только на клиенте (localStorage + navigator.language
// при самом первом заходе, см. src/content/lang.ts) — на сервере мы этого не знаем.
// Но метатеги (<title>, description, og:*, JSON-LD) рендерятся один раз на сервере
// и должны быть на каком-то языке ДО того, как клиентский JS вообще запустился —
// иначе поисковики и превью в соцсетях всегда будут видеть английский, даже когда
// сам сайт реально показывается на русском/румынском.
//
// Разбираем заголовок Accept-Language, который браузер сам присылает с каждым
// запросом (отражает системный/браузерный язык посетителя — тот же источник,
// на который ориентируется клиентский автоопределитель языка при первом визите).
// Это не идеально (не совпадёт, если человек вручную переключил язык на сайте
// на что-то отличное от языка браузера), но для метатегов и SEO — уже большой
// шаг вперёд по сравнению с постоянным английским.
export async function getServerLang(): Promise<Lang> {
  const headersList = await headers();
  const acceptLanguage = headersList.get("accept-language") ?? "";

  // Пример значения: "ru-RU,ru;q=0.9,en-US;q=0.8,en;q=0.7" — разбираем на
  // отдельные варианты, срезаем вес (;q=...), оставляем только сам код языка,
  // в порядке убывания предпочтения браузера.
  const preferred = acceptLanguage
    .split(",")
    .map((part) => part.split(";")[0].trim().slice(0, 2).toLowerCase());

  for (const code of preferred) {
    if (code === "ru" || code === "ro" || code === "en") {
      return code;
    }
  }

  return "en";
}
