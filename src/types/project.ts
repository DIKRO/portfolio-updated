import type { GalleryItem } from "@/lib/imageOrientation";

export type CategoryKey =
  | "branding"
  | "digital"
  | "print"
  | "packaging"
  | "ui-ux"
  | "video-editing"
  | "motion-design";

export interface LocalizedText {
  ru: string;
  en: string;
  ro: string;
}

export interface Project {
  id: string;
  slug: string;

  // Порядок показа именно на вкладке "Все работы" (и вообще в любом месте,
  // где список выводится без разбивки по категориям). Сейчас глобально
  // выстроен по категориям — так же, как в самих фильтрах (сначала весь
  // брендинг, потом анимация, digital и т.д.), просто сквозным номером без
  // пропусков (1, 2, 3…), меньшее число — раньше/выше в списке.
  //
  // ВАЖНО, ЧТОБЫ НЕ ЗАБЫТЬ: ничто не обязывает следовать этому порядку
  // строго — если захочешь вынести 2-3 конкретных проекта в самое начало
  // "Все работы" независимо от категории (например, показать самые сильные
  // работы первыми), просто дай им order поменьше (1, 2, 3), а остальным
  // сдвинь +1 — категорийный порядок для них сохранится, только эти
  // избранные окажутся впереди всех. См. пример прямо над массивом projects
  // ниже.
  order: number;

  title: LocalizedText;

  categoryKey: CategoryKey;

  year: number;

  cover: string;

  // Фото проекта — как раньше, просто строки-пути. Плюс, при необходимости
  // (актуально для категорий "video-editing"/"motion-design"), можно
  // вставить видео прямо в эту же последовательность: вместо строки —
  // объект { video, width, height }, например:
  //   images: [
  //     "/images/work/project/1.jpg",
  //     { video: "https://pub-xxxxxxxx.r2.dev/work/project/anim.mp4", width: 1080, height: 1920 },
  //     "/images/work/project/2.jpg",
  //   ]
  // width/height — реальные пропорции ролика (укажи сам, они нужны только
  // чтобы решить, встанет ли видео в пару с соседним портретным фото — на
  // видимый размер не влияют, растягивания/обрезки не будет в любом
  // случае). Видео в этой галерее не открывается в лайтбоксе (у него уже
  // есть свой плеер с полноэкранным режимом) — лайтбокс листает только фото.
  images: GalleryItem[];

  // Отдельное "главное" видео-превью проекта (обычно mp4) — необязательное
  // поле, для кейсов, где видео — основной/единственный показываемый
  // материал. Показывается САМЫМ ПЕРВЫМ блоком на странице проекта, сразу
  // после описания и перед галереей фото (images выше). Если нужно видео
  // ВМЕСТЕ с фото в общей раскладке — используй images (см. выше) вместо
  // или в дополнение к этому полю.
  // Файл НЕ кладём в public/ (см. договорённость про хранение видео вне
  // git-репозитория — Cloudflare R2), сюда — просто прямая ссылка на уже
  // захостенный файл, например:
  // "https://pub-xxxxxxxx.r2.dev/work/название-проекта/anim.mp4"
  video?: string;

  // Сплошной текст описания проекта — кратко расскажи, что сделал в этой работе.
  description: LocalizedText;

  // Необязательная короткая подпись-контекст под шапкой проекта — например
  // "В сотрудничестве с агентством N". Используй только когда это реально
  // важно указать (например, проект выполнен через агентство/по заказу
  // другой студии) — не для рядовых собственных/клиентских работ, и
  // осторожно с формулировками вроде "учебный проект": это может задать
  // клиенту неверную рамку восприятия работы. Показывается небольшим
  // акцентным (фирменный оранжевый) лейблом, прижатым к правому краю
  // строки категории/года (см. .contextLabel в ProjectView.module.css). Не
  // указывай поле вообще, если для этого проекта пометка не нужна — тогда
  // лейбл просто не рендерится.
  context?: LocalizedText;

  // Ключ клиента (см. CLIENTS в About.tsx, поле key) — если проект сделан
  // для компании из блока "С кем я сотрудничал", проставь тот же ключ
  // здесь. Тогда этот проект автоматически появится в карточке этого
  // клиента на странице "Обо мне", без необходимости где-то ещё вручную
  // прописывать его slug. Необязательное поле — просто не указывай, если
  // проект личный/не привязан ни к одному клиенту из этого блока.
  client?: string;
}
